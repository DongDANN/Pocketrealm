const blank = '00000';
function g(...rows: string[]): readonly string[] {
  if (rows.length !== 7) throw new Error(`Glyph needs 7 rows, got ${rows.length}`);
  for (const row of rows) if (row.length !== 5) throw new Error(`Glyph row must be 5 wide: ${row}`);
  return [blank, ...rows];
}

