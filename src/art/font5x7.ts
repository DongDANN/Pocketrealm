const FALLBACK = GLYPHS['?']!;

export function glyphFor(char: string): readonly string[] {
  const direct = GLYPHS[char];
  if (direct) return direct;
  const upper = char.toUpperCase();
  return GLYPHS[upper] ?? FALLBACK;
}

export function measureText(text: string): number {
  if (text.length === 0) return 0;
  return text.length * ADVANCE - 1;
}

export function drawText(
  target: Pixmap,
  x: number,
  y: number,
  text: string,
  color: number,
  scale = 1,
): void {
  let cursor = x;
  for (const char of text) {
    const glyph = glyphFor(char);
    for (let row = 0; row < GLYPH_H; row++) {
      const bits = glyph[row]!;
      for (let col = 0; col < GLYPH_W; col++) {
        if (bits[col] !== '1') continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            setPx(target, cursor + col * scale + sx, y + row * scale + sy, color);
          }
        }
      }
    }
    cursor += ADVANCE * scale;
  }
}

export function textPixmap(text: string, color: number, scale = 1, padding = 0): Pixmap {
  const w = Math.max(1, measureText(text) * scale + padding * 2);
  const h = GLYPH_H * scale + padding * 2;
  const out = createPixmap(w, h);
  drawText(out, padding, padding, text, color, scale);
  return out;
}
