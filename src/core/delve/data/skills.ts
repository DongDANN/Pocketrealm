export function skillById(id: string): CatalogueSkill | undefined {
  return SKILLS.find((s) => s.id === id);
}

export function skillsOfRarity(rarity: Rarity): CatalogueSkill[] {
  return SKILLS.filter((s) => s.rarity === rarity);
}

export function skillsWithTag(tag: BoonTag): CatalogueSkill[] {
  return SKILLS.filter((s) => s.tag === tag);
}
