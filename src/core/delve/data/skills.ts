/**
 * The skill catalogue (DELVE_REDESIGN §7 D.1): sixty original skills across the five rarity ramps,
 * each carrying one of the existing boon tags so the tag-chain multiplier from boons reaches the
 * moveset without inventing a second axis.
 *
 * This module is data and nothing else. Capsules, dust, levels and the four equipped slots all read
 * from it, and none of them live here — the catalogue has to stay answerable without knowing how it
 * gets into a player's hands.
 *
 * The counts are the contract, so the list is grouped by tag with its tier written next to each
 * entry: 22 common, 16 uncommon, 12 rare, 7 epic, 3 mythic. `tests/delve-skills-catalogue.test.ts`
 * fails if a tier drifts, which is the only reason the grouping is load-bearing rather than cosmetic.
 *
 * Every effect is written in the vocabulary `combat.ts` already honours (`SkillHitFx` / `PassiveFx`),
 * because a skill the resolver cannot honour is a promise the UI would have to break. The level-5
 * line is the one exception: §7 D.6 attaches a modifier at the top of the dust ladder, and it is
 * prose until 7c-3 gives it teeth.
 */

import type { BoonTag, Rarity } from '../types';
import type { PassiveFx, SkillDef, SkillHitFx } from './builds';
import type { Element } from './elements';

/** A catalogue entry: a combat skill plus the collection facts that put it in a capsule. */
export interface CatalogueSkill extends SkillDef {
  rarity: Rarity;
  /** The boon tag this skill chains with (§7 D.1). */
  tag: BoonTag;
  /** The modifier the top of the dust ladder attaches (§7 D.6). */
  level5: string;
}

/** Draw order matters to the odds table, so the tiers are named once, here. */
export const RARITIES: readonly Rarity[] = ['common', 'uncommon', 'rare', 'epic', 'mythic'];

function slug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function skill(def: Omit<CatalogueSkill, 'id'>): CatalogueSkill {
  return { id: `skill-${slug(def.name)}`, ...def };
}

function active(
  name: string,
  tag: BoonTag,
  rarity: Rarity,
  element: Element,
  energyCost: number,
  cooldown: number,
  power: number,
  effect: string,
  fx: SkillHitFx,
  level5: string,
  role?: 'guard' | 'burst',
): CatalogueSkill {
  return skill({
    name,
    kind: 'active',
    tag,
    rarity,
    element,
    energyCost,
    cooldown,
    power,
    effect,
    fx,
    level5,
    ...(role ? { role } : {}),
  });
}

function passive(
  name: string,
  tag: BoonTag,
  rarity: Rarity,
  effect: string,
  fx: PassiveFx,
  level5: string,
): CatalogueSkill {
  return skill({ name, kind: 'passive', tag, rarity, effect, fx, level5 });
}

